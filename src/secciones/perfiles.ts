/** El perfil de una serie y tamaño, o undefined. */
export function perfilDeCatalogo(serie: SeriePerfil, tamano: number): PerfilDeCatalogo | undefined {
  return PERFILES.find((p) => p.serie === serie && p.tamano === tamano);
}

/** El perfil del catálogo que es exactamente éste (los ocho valores), o undefined. */
export function enCatalogo(p: PerfilCatalogo): PerfilDeCatalogo | undefined {
  return PERFILES.find((x) => x.perfil.A === p.A && x.perfil.Iy === p.Iy && x.perfil.Iz === p.Iz && x.perfil.It === p.It && x.perfil.h === p.h && x.perfil.b === p.b && x.perfil.tf === p.tf && x.perfil.tw === p.tw);
}
